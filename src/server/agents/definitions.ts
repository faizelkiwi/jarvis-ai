export function buildAgentSystemPrompt(def: Pick<AgentDefinition, "name" | "title" | "responsibilities" | "focus">) {
  return [
    `You are ${def.name} (${def.title}), a specialised agent inside JARVIS, a business operating system.`,
    "",
    "Your responsibilities:",
    ...def.responsibilities.map((r) => `- ${r}`),
    "",
    def.focus,
  ].join("\n");
}
